#!/usr/bin/env python3
"""parse-win-triage.py - Offline Windows Endpoint Triage & RCA Analyzer

Deterministic diagnostic evaluation engine for Windows 10/11 and Windows Server
telemetry bundles generated by collect-win-triage.ps1.

Evaluates 6 core diagnostic domains:
  1. System stability, reboot hygiene & Fast Startup stale kernel sessions.
  2. Storage capacity, physical bad blocks (Event 7/153/55), and BitLocker posture.
  3. Kernel crashes (Event 41/1001 BSOD), application faults (1000/1002), and GPU TDR (4101).
  4. Modern Workplace identity (Entra PRT token missing), APIPA, and public DNS leaks.
  5. Hardware throttling (Event 37 CPU frequency capping) and battery wear.
  6. Critical stopped services and resource exhaustion (Event 2004).

Produces:
  - Executive Triage Verdict & "Can L1 Fix It Now?" determination.
  - Correlated findings table.
  - Non-destructive remediation commands with verification and rollback steps.
  - Pre-formatted L2/L3 escalation brief for ServiceNow/Jira.

Zero external dependencies - Python standard library only.
"""

